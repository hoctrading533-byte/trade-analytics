export function calculateTrade(trade) {
  const gross =
    trade.side === 'long'
      ? (trade.exitPrice - trade.entryPrice) * trade.volume
      : (trade.entryPrice - trade.exitPrice) * trade.volume
  const pnl = gross - trade.commission - trade.fee
  const risk = Math.abs(trade.entryPrice - trade.stopLoss) * trade.volume
  const reward = Math.abs(trade.takeProfit - trade.entryPrice) * trade.volume
  const entryMs = new Date(trade.entryTime).getTime()
  const exitMs = new Date(trade.exitTime).getTime()
  return {
    ...trade,
    pnl: Number(pnl.toFixed(2)),
    grossPnl: Number(gross.toFixed(2)),
    risk: Number(risk.toFixed(2)),
    reward: Number(reward.toFixed(2)),
    rMultiple: risk > 0 ? Number((pnl / risk).toFixed(2)) : 0,
    rr: risk > 0 ? Number((reward / risk).toFixed(2)) : 0,
    holdingMinutes: Math.max(1, Math.round((exitMs - entryMs) / 60000))
  }
}

