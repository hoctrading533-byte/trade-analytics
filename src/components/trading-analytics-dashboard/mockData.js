const MS_PER_DAY = 24 * 60 * 60 * 1000

function at(daysAgo, hour, minute = 0) {
  const date = new Date(Date.now() - daysAgo * MS_PER_DAY)
  date.setHours(hour, minute, 0, 0)
  return date.toISOString()
}

